// language saved by the user, English by default
const getActiveLanguage = () => {
    const saved = localStorage.getItem('language');
    if (saved === 'en' || saved === 'pt') return saved; // the user already chose one
    return navigator.language.startsWith('pt') ? 'pt' : 'en';
};

// returns the text for a key, or the key itself if it's missing
const t = (key) => TRANSLATIONS[getActiveLanguage()]?.[key] ?? key;

// language code used by Intl and toLocaleDateString
const getLocale = () => getActiveLanguage() === 'pt' ? 'pt-PT' : 'en-GB';

// translated name of a category, the stored value never changes
const tCat = (cat) => cat === GENERAL_BUDGET_CAT ? t('budget.general') : t('cat.' + cat);

// fills every element that has a data-i18n attribute
const applyTranslations = (root = document) => {
    root.querySelectorAll('[data-i18n]').forEach(el => {
        el.textContent = t(el.dataset.i18n);
    });

    root.querySelectorAll('[data-i18n-aria]').forEach(el => {
        el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });

    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = t(el.dataset.i18nPlaceholder);
    });
};

